# Считываем два целых числа
a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))

# Вложенные условия
if a > b:
    print("Первое число больше второго")
else:
    if a < b:
        print("Второе число больше первого")
    else:
        print("Числа равны")